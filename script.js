// --- Typing Effect ---
const typingTextElement = document.querySelector('.typing-text');
let words = typingWords[currentLang];
let wordIndex = 0;
let charIndex = 0;
let isDeleting = false;
let typingTimer = null;

function typeEffect() {
    if (!typingTextElement) return;
    const currentWord = words[wordIndex % words.length];
    
    if (isDeleting) {
        typingTextElement.textContent = currentWord.substring(0, charIndex - 1);
        charIndex--;
    } else {
        typingTextElement.textContent = currentWord.substring(0, charIndex + 1);
        charIndex++;
    }

    let typeSpeed = isDeleting ? 50 : 100;

    if (!isDeleting && charIndex === currentWord.length) {
        typeSpeed = 2000; // Pause at end of word
        isDeleting = true;
    } else if (isDeleting && charIndex <= 0) {
        isDeleting = false;
        wordIndex = (wordIndex + 1) % words.length;
        typeSpeed = 500; // Pause before typing new word
    }

    clearTimeout(typingTimer);
    typingTimer = setTimeout(typeEffect, typeSpeed);
}

// --- Language Switcher Function ---
function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('preferred_lang', lang);
    document.documentElement.lang = lang;

    // Update Title & Meta
    if (translations[lang].page_title) {
        document.title = translations[lang].page_title;
    }
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && translations[lang].meta_desc) {
        metaDesc.setAttribute('content', translations[lang].meta_desc);
    }

    // Update Text Elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key] !== undefined) {
            element.innerHTML = translations[lang][key];
        }
    });

    // Update Form Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[lang][key] !== undefined) {
            element.setAttribute('placeholder', translations[lang][key]);
        }
    });

    // Update Switcher Active Button State
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Update Typing Animation Words
    if (typingWords[lang]) {
        words = typingWords[lang];
        wordIndex = 0;
        charIndex = 0;
        isDeleting = false;
        if (typingTextElement) {
            typingTextElement.textContent = '';
        }
        if (typingTimer) {
            clearTimeout(typingTimer);
        }
        typingTimer = setTimeout(typeEffect, 300);
    }

    // Update Astronaut Quote for current language
    const bubbleText = document.querySelector('.bubble-text');
    if (bubbleText && astronautQuotes[lang]) {
        bubbleText.textContent = astronautQuotes[lang][0];
    }
}

// --- Astronaut Companion Logic with Horizontal Spacewalk Patrol ---
const astronaut = document.getElementById('astronaut-companion');
const bubbleText = document.querySelector('.bubble-text');
const astronautBubble = document.querySelector('.astronaut-bubble');
let lastScrollY = window.scrollY;
let quoteIndex = 0;

if (astronaut) {
    let currentX = 0;
    let targetX = 0;
    let lastX = 0;
    let scrollTilt = 0;

    function updateAstronautPatrol() {
        const time = Date.now() * 0.0006;
        const maxWidth = Math.min(window.innerWidth - 140, 750);
        
        const maxScroll = (document.documentElement.scrollHeight - window.innerHeight) || 1;
        const scrollRatio = window.scrollY / maxScroll;
        
        const sineWave = (Math.sin(time) + 1) / 2;
        const patrolProgress = (sineWave * 0.6) + (scrollRatio * 0.4); 
        
        targetX = patrolProgress * maxWidth;
        
        // LERP
        currentX += (targetX - currentX) * 0.04;
        
        const moveDelta = currentX - lastX;
        lastX = currentX;

        const svgContainer = astronaut.querySelector('.astronaut-svg-container');
        if (svgContainer) {
            let flipScale = 1;
            if (moveDelta > 0.05) {
                flipScale = 1;
            } else if (moveDelta < -0.05) {
                flipScale = -1;
            } else {
                flipScale = parseFloat(astronaut.dataset.flip) || 1;
            }
            astronaut.dataset.flip = flipScale;

            astronaut.style.transform = `translate3d(-${currentX}px, 0px, 0px)`;
            svgContainer.style.transform = `scaleX(${flipScale}) rotate(${scrollTilt}deg)`;
        }

        requestAnimationFrame(updateAstronautPatrol);
    }

    requestAnimationFrame(updateAstronautPatrol);

    window.addEventListener('scroll', () => {
        const currentScrollY = window.scrollY;
        const delta = currentScrollY - lastScrollY;
        lastScrollY = currentScrollY;

        scrollTilt = Math.max(Math.min(delta * 0.4, 25), -25);

        clearTimeout(astronaut.tiltTimer);
        astronaut.tiltTimer = setTimeout(() => {
            scrollTilt = 0;
        }, 150);
    });

    astronaut.addEventListener('click', () => {
        window.scrollTo({
            top: 0,
            behavior: 'smooth'
        });

        const quotes = astronautQuotes[currentLang] || astronautQuotes.id;
        quoteIndex = (quoteIndex + 1) % quotes.length;
        if (bubbleText) {
            bubbleText.textContent = quotes[quoteIndex];
        }

        if (astronautBubble) {
            astronautBubble.classList.add('show');
            clearTimeout(astronaut.bubbleTimer);
            astronaut.bubbleTimer = setTimeout(() => {
                astronautBubble.classList.remove('show');
            }, 3000);
        }
    });
}

// --- Interactive Space Particle Canvas ---
class SpaceParticleCanvas {
    constructor() {
        this.canvas = document.getElementById('space-canvas');
        if (!this.canvas) return;
        this.ctx = this.canvas.getContext('2d');
        this.particles = [];
        this.particleCount = Math.min(Math.floor(window.innerWidth / 18), 70);
        this.mouse = { x: null, y: null, radius: 120 };

        this.init();
        this.animate();
        this.bindEvents();
    }

    init() {
        this.resize();
        this.particles = [];
        for (let i = 0; i < this.particleCount; i++) {
            this.particles.push({
                x: Math.random() * this.canvas.width,
                y: Math.random() * this.canvas.height,
                vx: (Math.random() - 0.5) * 0.6,
                vy: (Math.random() - 0.5) * 0.6,
                radius: Math.random() * 1.8 + 0.8,
                color: Math.random() > 0.5 ? 'rgba(6, 182, 212, ' : 'rgba(99, 102, 241, ',
                alpha: Math.random() * 0.7 + 0.3
            });
        }
    }

    resize() {
        this.canvas.width = window.innerWidth;
        this.canvas.height = window.innerHeight;
    }

    bindEvents() {
        window.addEventListener('resize', () => this.init());
        window.addEventListener('mousemove', (e) => {
            this.mouse.x = e.clientX;
            this.mouse.y = e.clientY;
        });
        window.addEventListener('mouseleave', () => {
            this.mouse.x = null;
            this.mouse.y = null;
        });
    }

    animate() {
        this.ctx.clearRect(0, 0, this.canvas.width, this.canvas.height);

        for (let i = 0; i < this.particles.length; i++) {
            const p = this.particles[i];
            p.x += p.vx;
            p.y += p.vy;

            if (p.x < 0) p.x = this.canvas.width;
            if (p.x > this.canvas.width) p.x = 0;
            if (p.y < 0) p.y = this.canvas.height;
            if (p.y > this.canvas.height) p.y = 0;

            // Render Star Particle
            this.ctx.beginPath();
            this.ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            this.ctx.fillStyle = p.color + p.alpha + ')';
            this.ctx.fill();

            // Connect nearby stars with constellation lines
            for (let j = i + 1; j < this.particles.length; j++) {
                const p2 = this.particles[j];
                const dx = p.x - p2.x;
                const dy = p.y - p2.y;
                const dist = Math.sqrt(dx * dx + dy * dy);

                if (dist < 100) {
                    this.ctx.beginPath();
                    this.ctx.moveTo(p.x, p.y);
                    this.ctx.lineTo(p2.x, p2.y);
                    this.ctx.strokeStyle = `rgba(99, 102, 241, ${0.15 * (1 - dist / 100)})`;
                    this.ctx.lineWidth = 0.6;
                    this.ctx.stroke();
                }
            }

            // Mouse repulsion
            if (this.mouse.x !== null) {
                const mdx = p.x - this.mouse.x;
                const mdy = p.y - this.mouse.y;
                const mdist = Math.sqrt(mdx * mdx + mdy * mdy);
                if (mdist < this.mouse.radius) {
                    const angle = Math.atan2(mdy, mdx);
                    const force = (this.mouse.radius - mdist) / this.mouse.radius;
                    p.x += Math.cos(angle) * force * 2;
                    p.y += Math.sin(angle) * force * 2;
                }
            }
        }

        requestAnimationFrame(() => this.animate());
    }
}

// --- Custom Neon Space Cursor ---
function initCustomCursor() {
    const cursor = document.getElementById('custom-cursor');
    const follower = document.getElementById('custom-cursor-follower');
    if (!cursor || !follower) return;

    let posX = 0, posY = 0;
    let mouseX = 0, mouseY = 0;

    window.addEventListener('mousemove', (e) => {
        mouseX = e.clientX;
        mouseY = e.clientY;
        cursor.style.left = `${mouseX}px`;
        cursor.style.top = `${mouseY}px`;
    });

    function renderCursorFollower() {
        posX += (mouseX - posX) * 0.15;
        posY += (mouseY - posY) * 0.15;
        follower.style.left = `${posX}px`;
        follower.style.top = `${posY}px`;
        requestAnimationFrame(renderCursorFollower);
    }
    renderCursorFollower();

    // Hover effect on interactive elements
    const interactiveElements = document.querySelectorAll('a, button, .project-card, .skill-card, .achievement-card, .lang-btn, .astronaut-companion');
    interactiveElements.forEach(el => {
        el.addEventListener('mouseenter', () => document.body.classList.add('cursor-hover'));
        el.addEventListener('mouseleave', () => document.body.classList.remove('cursor-hover'));
    });
}

// --- Project Category Filter Logic ---
function initProjectFilters() {
    const filterBtns = document.querySelectorAll('.filter-btn');
    const projectCards = document.querySelectorAll('.project-card');

    filterBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            filterBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');

            const filter = btn.getAttribute('data-filter');

            projectCards.forEach(card => {
                const category = card.getAttribute('data-category');
                if (filter === 'all' || category === filter) {
                    card.classList.remove('hide');
                } else {
                    card.classList.add('hide');
                }
            });
        });
    });
}

// --- Project & Certificate Lightbox Modals ---
function initModals() {
    const projectModal = document.getElementById('project-modal');
    const certModal = document.getElementById('certificate-modal');
    
    // Project Modal Opener Buttons
    document.querySelectorAll('.btn-project-modal').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const projectKey = btn.getAttribute('data-project');
            const data = projectDetails[projectKey];
            if (!data) return;

            document.getElementById('modal-category').textContent = data.category[currentLang] || data.category.id;
            document.getElementById('modal-title').textContent = data.title;
            document.getElementById('modal-img').src = data.img;
            document.getElementById('modal-desc').textContent = data.desc[currentLang] || data.desc.id;

            // Render Tags
            const tagsContainer = document.getElementById('modal-tags');
            tagsContainer.innerHTML = data.tags.map(tag => `<span>${tag}</span>`).join('');

            // Render Features
            const featuresContainer = document.getElementById('modal-features');
            const featuresList = data.features[currentLang] || data.features.id;
            featuresContainer.innerHTML = featuresList.map(feat => `<li>${feat}</li>`).join('');

            projectModal.classList.add('active');
            projectModal.setAttribute('aria-hidden', 'false');
        });
    });

    // Certificate Modal Opener Cards
    document.querySelectorAll('.cert-card').forEach(card => {
        card.addEventListener('click', () => {
            const imgSrc = card.getAttribute('data-cert-img');
            const caption = card.getAttribute('data-cert-title');

            document.getElementById('cert-img').src = imgSrc;
            document.getElementById('cert-caption').textContent = caption;

            certModal.classList.add('active');
            certModal.setAttribute('aria-hidden', 'false');
        });
    });

    // Close Modals
    document.querySelectorAll('.modal-close, .modal-overlay').forEach(overlay => {
        overlay.addEventListener('click', (e) => {
            if (e.target === overlay || e.target.classList.contains('modal-close')) {
                projectModal.classList.remove('active');
                projectModal.setAttribute('aria-hidden', 'true');
                certModal.classList.remove('active');
                certModal.setAttribute('aria-hidden', 'true');
            }
        });
    });
}

// --- Scroll Reveal Animation ---
const revealElements = document.querySelectorAll('.reveal');

const revealCallback = (entries, observer) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('active');
            
            // Trigger progress bars if inside skills section
            if (entry.target.classList.contains('skills-grid')) {
                const progressBars = entry.target.querySelectorAll('.progress');
                progressBars.forEach(bar => {
                    bar.style.width = bar.getAttribute('data-width');
                });
            }
            
            // Trigger counters if inside about section
            if (entry.target.classList.contains('about-content')) {
                const counters = entry.target.querySelectorAll('.counter');
                counters.forEach(counter => {
                    counterAnim(counter);
                });
            }
            
            observer.unobserve(entry.target);
        }
    });
};

const revealOptions = {
    threshold: 0.15,
    rootMargin: "0px 0px -50px 0px"
};

const revealObserver = new IntersectionObserver(revealCallback, revealOptions);

revealElements.forEach(el => {
    revealObserver.observe(el);
});

// --- Counter Animation ---
function counterAnim(element) {
    const target = +element.getAttribute('data-target');
    const duration = 2000; // 2 seconds
    const increment = target / (duration / 16); // 60fps
    let current = 0;

    const updateCounter = () => {
        current += increment;
        if (current < target) {
            element.innerText = Math.ceil(current) + "+";
            requestAnimationFrame(updateCounter);
        } else {
            element.innerText = target + "+";
        }
    };
    updateCounter();
}

// --- 3D Tilt Effect on Project Cards ---
const tiltCards = document.querySelectorAll('.tilt');

tiltCards.forEach(card => {
    card.addEventListener('mousemove', (e) => {
        const rect = card.getBoundingClientRect();
        const x = e.clientX - rect.left;
        const y = e.clientY - rect.top;
        
        const centerX = rect.width / 2;
        const centerY = rect.height / 2;
        
        const rotateX = ((y - centerY) / centerY) * -10;
        const rotateY = ((x - centerX) / centerX) * 10;
        
        card.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale3d(1.02, 1.02, 1.02)`;
    });
    
    card.addEventListener('mouseleave', () => {
        card.style.transform = `perspective(1000px) rotateX(0deg) rotateY(0deg) scale3d(1, 1, 1)`;
        card.style.transition = 'transform 0.5s ease';
    });
    
    card.addEventListener('mouseenter', () => {
        card.style.transition = 'none';
    });
});

// --- Smooth Scrolling for Anchor Links ---
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const targetId = this.getAttribute('href');
        if (targetId === '#') return;
        
        const targetElement = document.querySelector(targetId);
        if (targetElement) {
            const headerOffset = 80;
            const elementPosition = targetElement.getBoundingClientRect().top;
            const offsetPosition = elementPosition + window.scrollY - headerOffset;
  
            window.scrollTo({
                top: offsetPosition,
                behavior: "smooth"
            });
        }
    });
});

